"""Reuse licensed CJK shards; subset the fixed plaza title and running wordmark.

Requires fonttools and brotli. Full upstream WOFF2 sources are cached locally
in .cache/plaza-font-sources; no upstream downloads or full fonts are published.
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'public/assets/fonts/events'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rules = [line.replace('font-display:swap', 'font-display:optional')
             for line in (ROOT / 'public/styles/font-faces.css').read_text(encoding='utf-8').splitlines()
             if 'font-family:"NJU Heading"' in line]
    manifest = []
    for name, family, source, text, weight in [
        ('title', 'Events Serif', 'noto-serif-sc-full.woff2', '把善意，化作行动人道 · 博爱 · 奉献', '200 900'),
        ('wordmark', 'Events Running', 'zhi-mang-xing-full.woff2', '南京大学红十字会', '400'),
    ]:
        source_path = ROOT / '.cache/plaza-font-sources' / source
        font = TTFont(source_path, recalcTimestamp=False)
        options = subset.Options()
        options.layout_features = ['*']
        worker = subset.Subsetter(options=options)
        worker.populate(text=text)
        worker.subset(font)
        font.flavor = 'woff2'
        target = OUT / (name + '.woff2')
        font.save(target)
        rules.append(f"@font-face{{font-family:'{family}';src:url('/assets/fonts/events/{name}.woff2') format('woff2');font-style:normal;font-weight:{weight};font-display:optional;}}")
        manifest.append(dict(family=family, source=source, sourceSha256=hashlib.sha256(source_path.read_bytes()).hexdigest(), characters=''.join(sorted(set(text))), bytes=target.stat().st_size, sha256=hashlib.sha256(target.read_bytes()).hexdigest(), license='SIL OFL 1.1'))
    (ROOT / 'public/styles/events-fonts.css').write_text('/* Generated by scripts/build-events-typography.py; OFL fonts, demand-loaded Chinese shards. */\n' + '\n'.join(rules) + '\n', encoding='utf-8')
    (OUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(manifest, ensure_ascii=False))


if __name__ == '__main__':
    main()
