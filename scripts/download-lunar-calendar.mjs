/** Download only public HKO calendar data; no account, database or mail access. */
import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const sources = [];
const months = [];
for (let year = 2026; year <= 2030; year++) {
  const url = `https://www.hko.gov.hk/en/gts/time/calendar/text/files/T${year}e.txt`;
  const response = await fetch(url, { signal: AbortSignal.timeout(40000) });
  if (!response.ok) throw new Error(`calendar_download_failed:${year}`);
  const text = await response.text();
  sources.push({ year, url, sha256: createHash('sha256').update(text).digest('hex') });
  const rows = [...text.matchAll(/^(\d{4})\/(\d+)\/(\d+)\s+(.+?)\s{2,}/gm)];
  const expected = (Date.UTC(year + 1, 0, 1) - Date.UTC(year, 0, 1)) / 86400000;
  if (rows.length !== expected) throw new Error(`calendar_day_count_invalid:${year}`);
  for (let index = 0; index < rows.length; index++) {
    const [, y, m, d, lunar] = rows[index];
    const timestamp = Date.UTC(Number(y), Number(m) - 1, Number(d));
    if (timestamp !== Date.UTC(year, 0, 1) + index * 86400000) throw new Error('calendar_dates_not_contiguous');
    const heading = lunar.match(/^(\d+)(?:st|nd|rd|th) Lunar Month$/);
    if (!months.length) {
      const nextMonth = rows.find(row => /Lunar Month/.test(row[4]))?.[4].match(/^(\d+)/);
      if (!nextMonth || Number(nextMonth[1]) < 2) throw new Error('calendar_initial_month_invalid');
      months.push({ start: new Date(timestamp - (Number(lunar) - 1) * 86400000).toISOString().slice(0, 10), month: Number(nextMonth[1]) - 1, leap: false });
    }
    if (heading) {
      const month = Number(heading[1]);
      const prior = months.at(-1);
      months.push({ start: new Date(timestamp).toISOString().slice(0, 10), month, leap: prior.month === month });
    } else {
      const actualDay = (timestamp - Date.parse(months.at(-1).start)) / 86400000 + 1;
      if (Number(lunar) !== actualDay || actualDay > 30) throw new Error('calendar_lunar_day_invalid');
    }
  }
}
for (let index = 0; index < months.length - 1; index++) {
  const days = (Date.parse(months[index + 1].start) - Date.parse(months[index].start)) / 86400000;
  if (![29, 30].includes(days)) throw new Error('calendar_month_length_invalid');
  months[index].days = days;
}
const data = { provider: 'Hong Kong Observatory', start: '2026-01-01', end: '2030-12-31', sources, months };
await writeFile(new URL('../lib/community/data/lunar-calendar-2026-2030.js', import.meta.url), `// Public HKO calendar data; generated by scripts/download-lunar-calendar.mjs.\nexport default ${JSON.stringify(data, null, 2)};\n`);
console.log(`Saved ${months.length} lunar month boundaries (2026–2030).`);
