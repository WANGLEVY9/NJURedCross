"""Build licensed, pinned web subsets: pip install fonttools brotli.

Core contains characters used by the application. GB2312 characters remain
available in on-demand shards; rare characters use the platform font fallback.
Generated derivatives use NJU names to respect Source's reserved font name.
"""
import hashlib
import io
import json
import pathlib
import tempfile
import urllib.request
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'public/assets/fonts/roles'
CACHE = pathlib.Path(tempfile.gettempdir()) / 'nju-font-sources'
SOURCES = [
    ('sans', 'NJU Heading', 400, 'adobe-fonts/source-han-sans', 'a4f7cf94edfb9d7ffbdfc4841de276358bd7e0f2', 'OTF/SimplifiedChinese/SourceHanSansSC-Regular.otf', 'LICENSE.txt'),
    ('sans', 'NJU Heading', 700, 'adobe-fonts/source-han-sans', 'a4f7cf94edfb9d7ffbdfc4841de276358bd7e0f2', 'OTF/SimplifiedChinese/SourceHanSansSC-Bold.otf', 'LICENSE.txt'),
    ('serif', 'NJU Information', 400, 'adobe-fonts/source-han-serif', '7889f11bf31170b5d092a083b357c8c8130f89e0', 'OTF/SimplifiedChinese/SourceHanSerifSC-Regular.otf', 'LICENSE.txt'),
    ('serif', 'NJU Information', 700, 'adobe-fonts/source-han-serif', '7889f11bf31170b5d092a083b357c8c8130f89e0', 'OTF/SimplifiedChinese/SourceHanSerifSC-Bold.otf', 'LICENSE.txt'),
    ('kai', 'NJU Annotation', 400, 'lxgw/LxgwWenKai', 'd582f24504099b8e6d161bdd5e8fd3ae3ab63462', 'fonts/TTF/LXGWWenKai-Regular.ttf', 'OFL.txt'),
]


def download(url):
    path = CACHE / hashlib.sha256(url.encode()).hexdigest()
    if not path.exists():
        with urllib.request.urlopen(url, timeout=180) as response:
            path.write_bytes(response.read())
    return path.read_bytes()


def unicode_ranges(points):
    ranges = []
    start = end = None
    for point in sorted(points):
        if end is not None and point == end + 1:
            end = point
        else:
            if start is not None:
                ranges.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
            start = end = point
    if start is not None:
        ranges.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
    return ','.join(ranges)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    CACHE.mkdir(parents=True, exist_ok=True)
    chinese = set()
    for high in range(0xA1, 0xF8):
        for low in range(0xA1, 0xFF):
            try:
                chinese.add(ord(bytes((high, low)).decode('gb2312')))
            except UnicodeDecodeError:
                pass
    common = set()
    for path in (ROOT / 'public').rglob('*'):
        if path.suffix in ('.js', '.html'):
            common.update(ord(c) for c in path.read_text() if ord(c) >= 0x3000)
    common.update(range(0x3000, 0x3040))
    css = ['/* Generated by scripts/build-web-fonts.py; pinned sources and licenses in roles/manifest.json. */']
    manifest = []
    for slug, family, weight, repo, revision, source, license_name in SOURCES:
        base = f'https://raw.githubusercontent.com/{repo}/{revision}/'
        raw = download(base + source)
        license_text = download(base + license_name).decode('utf-8')
        (OUT / f'{slug}-LICENSE.txt').write_text('\n'.join(line.rstrip() for line in license_text.splitlines()) + '\n')
        original = TTFont(io.BytesIO(raw))
        # Latin is deliberately resolved by Times New Roman, not these CJK faces.
        supported = {u for u in original.getBestCmap() if u >= 0x3000 and u in chinese | common}
        core = supported & common
        remainder = supported - core
        groups = [('core', core)]
        for block in sorted({u // 1024 for u in remainder}):
            groups.append((f'{block:03x}', {u for u in remainder if u // 1024 == block}))
        files = []
        for label, points in groups:
            font = TTFont(io.BytesIO(raw))
            options = subset.Options()
            options.flavor = 'woff2'
            options.layout_features = ['kern', 'locl', 'ccmp', 'mark', 'mkmk']
            options.recalc_timestamp = False
            sub = subset.Subsetter(options=options)
            sub.populate(unicodes=points)
            sub.subset(font)
            for record in font['name'].names:
                if record.nameID in (1, 3, 4, 6, 16, 17):
                    text = family.replace(' ', '') + str(weight) if record.nameID == 6 else family + ' ' + str(weight)
                    record.string = text.encode(record.getEncoding())
            if 'CFF ' in font:
                cff = font['CFF '].cff
                cff.fontNames = [family.replace(' ', '') + str(weight)]
                for top in cff.topDictIndex:
                    top.FamilyName = family
                    top.FullName = family + ' ' + str(weight)
            font.flavor = 'woff2'
            filename = f'{slug}-{weight}-{label}.woff2'
            font.save(OUT / filename)
            css.append(f'@font-face{{font-family:"{family}";font-style:normal;font-weight:{weight};font-display:swap;src:url("/assets/fonts/roles/{filename}") format("woff2");unicode-range:{unicode_ranges(points)};}}')
            files.append({'file': filename, 'bytes': (OUT / filename).stat().st_size, 'characters': len(points)})
        manifest.append({'family': family, 'weight': weight, 'source': base + source, 'sha256': hashlib.sha256(raw).hexdigest(), 'license': f'{slug}-LICENSE.txt', 'files': files})
        print(f'{family} {weight}: {len(supported)} characters, {len(files)} shards', flush=True)
    (OUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'public/styles/font-faces.css').write_text('\n'.join(css) + '\n')


if __name__ == '__main__':
    main()
